export const DUO_ICONS = DUO_ICONS_RAW.map(item => ({
    ...item,
    id: `duo:${item.name}`,
    name: `duo:${item.name}`,
    rawName: item.name,
    library: 'duo',
    component: DuoIcons[item.name] || null
})).filter(item => Boolean(item.component));

const DUO_MAP = new Map();
DUO_ICONS.forEach(item => {
    DUO_MAP.set(item.rawName, item.component);
    DUO_MAP.set(item.rawName.toLowerCase(), item.component);
    DUO_MAP.set(`duo:${item.rawName}`, item.component);
    DUO_MAP.set(`duo:${item.rawName}`.toLowerCase(), item.component);
    DUO_MAP.set(`duo-${item.rawName}`, item.component);
    DUO_MAP.set(`duo-${item.rawName}`.toLowerCase(), item.component);
});

export function isDuoIconName(name) {
    if (!name || typeof name !== 'string') return false;
    if (name.startsWith('duo:') || name.startsWith('duo-')) return true;
    return DUO_MAP.has(name);
}

export function getDuoIconComponent(name) {
    if (!name) return null;
    let rawName = typeof name === 'object' && name !== null ? name.name : name;
    if (typeof rawName !== 'string') return null;
    return DUO_MAP.get(rawName) || DUO_MAP.get(rawName.toLowerCase()) || null;
}

export function getAllDuoIcons() {
    return DUO_ICONS;
}
